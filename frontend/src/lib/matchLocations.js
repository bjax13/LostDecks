function toRegionOptions(pairs) {
  return pairs
    .map(([code, name]) => ({ code, name }))
    .sort((a, b) => a.name.localeCompare(b.name, "en"));
}

const SUBDIVISIONS_BY_COUNTRY = {
  US: toRegionOptions(US_STATES),
  CA: toRegionOptions(CA_REGIONS),
  AU: toRegionOptions(AU_REGIONS),
  GB: toRegionOptions(GB_REGIONS),
};

const COUNTRY_CODES = new Set(MATCH_COUNTRY_LIST.map((country) => country.code));

export const MATCH_COUNTRIES = Object.freeze(
  MATCH_COUNTRY_LIST.slice().sort((a, b) => a.name.localeCompare(b.name, "en")),
);

export function normalizeMatchCountry(value) {
  if (typeof value !== "string") {
    return "";
  }
  const code = value.trim().toUpperCase();
  return COUNTRY_CODES.has(code) ? code : "";
}

export function subdivisionsForCountry(countryCode) {
  const country = normalizeMatchCountry(countryCode);
  const list = SUBDIVISIONS_BY_COUNTRY[country];
  return list ? list.map((entry) => ({ ...entry })) : [];
}

export function normalizeMatchRegion(countryCode, value) {
  const country = normalizeMatchCountry(countryCode);
  if (!country || typeof value !== "string") {
    return "";
  }
  const code = value.trim().toUpperCase();
  const list = SUBDIVISIONS_BY_COUNTRY[country];
  if (!list?.some((entry) => entry.code === code)) {
    return "";
  }
  return code;
}

/** Changing country always clears the state, including when the country is cleared. */
export function locationSelectionForCountry(countryCode) {
  return {
    matchCountry: normalizeMatchCountry(countryCode),
    matchRegion: "",
  };
}
